import { notFound } from "next/navigation";
import ArticleView from "@/components/article/ArticleView";
import Sidebar from "@/components/layout/Sidebar";
import JsonLd from "@/components/seo/JsonLd";
import { getArticle, getArticleSlugs, getAuthor, getCategory, getRelatedArticles } from "@/lib/content";
import { absoluteUrl } from "@/lib/site";
import { articleDates, articleJsonLd, pageMetadata } from "@/lib/seo";

// Fully static output; unknown slugs render completely first, so notFound() returns a real 404.
// Articles published later from the dashboard are generated on their first request and cached.
export const ensureStatic = "navigation";
export const instant = false;

export async function generateStaticParams() {
  const slugs = await getArticleSlugs();
  // Cache Components requires at least one param; the placeholder renders a 404.
  return slugs.length ? slugs.map((slug) => ({ slug })) : [{ slug: "no-articles-yet" }];
}

export async function generateMetadata({ params }) {
  const { slug } = await params;
  const article = await getArticle(slug);
  if (!article) return { title: "Article not found", robots: { index: false } };
  const [author, category] = await Promise.all([getAuthor(article.author), getCategory(article.category)]);
  const { published, modified } = articleDates(article);
  // Generated by app/blog/[slug]/opengraph-image.js, which sits outside the (site)
  // group so its URL stays /blog/<slug>/opengraph-image.
  const ogImage = { url: `/blog/${article.slug}/opengraph-image`, width: 1200, height: 630, alt: "Article title card", type: "image/png" };
  const base = pageMetadata({
    title: article.seo?.title || article.title,
    description: article.seo?.description || article.description,
    path: `/blog/${article.slug}`,
    canonical: article.seo?.canonical || undefined,
    ogType: "article",
    noIndex: article.status !== "published",
    images: [ogImage],
  });
  return {
    ...base,
    twitter: { ...base.twitter, images: [ogImage] },
    ...(author ? { authors: [{ name: author.name, url: absoluteUrl(`/authors/${author.slug}`) }] } : {}),
    keywords: article.tags,
    openGraph: {
      ...base.openGraph,
      type: "article",
      publishedTime: published,
      modifiedTime: modified,
      section: category?.name,
      tags: article.tags,
      ...(author ? { authors: [absoluteUrl(`/authors/${author.slug}`)] } : {}),
    },
  };
}

export default async function ArticlePage({ params }) {
  const { slug } = await params;
  const article = await getArticle(slug);
  if (!article) notFound();

  const [author, reviewer, category, related] = await Promise.all([
    getAuthor(article.author),
    article.review.reviewedBy ? getAuthor(article.review.reviewedBy) : null,
    getCategory(article.category),
    getRelatedArticles(article, 3),
  ]);

  return (
    <>
      <JsonLd data={articleJsonLd(article, author, category)} />
      <ArticleView
        article={article}
        author={author}
        reviewer={reviewer}
        category={category}
        related={related}
        url={absoluteUrl(`/blog/${article.slug}`)}
        sidebar={<Sidebar excludeSlug={article.slug} />}
      />
    </>
  );
}
